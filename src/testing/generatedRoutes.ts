import { describe, expect, it } from 'vitest'
import { createMemoryHistory, createRouter, type RouteRecordRaw } from 'vue-router'
import { parseTypedRouterDeclaration } from '@/testing/typedRouter'

// One value per id shape the admins constrain a param to: an integer id, a uuid (any version, the
// backends make v4, v6 and v7) and a log's Mongo ObjectId.
const PARAM_SAMPLES = ['1', '00000000-0000-4000-8000-000000000001', '000000000000000000000001']

export interface DescribeGeneratedRoutesOptions {
  /** `routes` from `vue-router/auto-routes`. */
  routes: RouteRecordRaw[]
  declaration: string
  /** `Object.keys(import.meta.glob('/src/pages/**\/*.vue'))`. */
  pageFiles: string[]
  /** The catch-all's param, whose route is left out. */
  catchAll?: string
}

/**
 * A smoke test over every generated route.
 * `anzu/valid-route-name` checks that a referenced name exists, not that the route can be reached. A
 * path whose constraint never matches, or one shadowed by an earlier record, still has a valid name.
 * Navigating to it lands on the catch-all, which renders a 404 page and throws nothing.
 * Importing `vue-router/auto-routes` is also part of the test: it loads every page
 * component and their stores, api clients and composables, so errors thrown at module
 * evaluation fail here. This needs `importMode` to be `sync` in the admin's vitest config.
 */
export function describeGeneratedRoutes({
  routes,
  declaration,
  pageFiles,
  catchAll = 'pathMatch',
}: DescribeGeneratedRoutesOptions): void {
  const declaredPaths = parseTypedRouterDeclaration(declaration).paths.filter(({ path }) => !path.includes(catchAll))
  const router = createRouter({ history: createMemoryHistory(), routes })

  // A constrained param (`:id(\d+)`, a uuid, an ObjectId) must be filled with a value its
  // regex accepts. Otherwise the route fails to match for a reason unrelated to the route.
  // The value is the first sample the regex takes, else `sample`.
  // The trailing `?` of an optional param is removed too. Left in place it starts a query
  // string, and the rest of the path (`/edit` in `/articles/:docId/:version?/edit`) is lost.
  const fillParams = (path: string) =>
    path.replace(/:[a-zA-Z]+(?:\(((?:\\.|[^\\)])*)\))?\??/g, (_match, regex?: string) =>
      regex
        ? // vue-router reads `\)` as a group's closing parenthesis inside a custom regex, `RegExp` would not.
          (PARAM_SAMPLES.find((sample) => new RegExp(`^(?:${regex.replace(/\\\)/g, ')')})$`, 'i').test(sample)) ??
          'sample')
        : 'sample'
    )

  describe('generated routes', () => {
    it('declares exactly the pages that exist on disk', () => {
      // Guards the guard: if the declaration were missing or the regex stopped
      // matching, the assertions below would iterate an empty list and pass.
      // Counted from disk instead of a literal, so it does not go stale when pages
      // change. The one page file `declaredPaths` filters out is the catch-all.
      expect(declaredPaths.length).toBe(pageFiles.length - 1)
    })

    it.each(declaredPaths)('resolves $path to its own record, not the catch-all', ({ name, path }) => {
      const resolved = router.resolve(fillParams(path))

      expect(resolved.matched.some((record) => record.path.includes(catchAll))).toBe(false)
      expect(resolved.name).toBe(name)
    })

    it('has a runtime route for every declared one, and nothing extra', () => {
      // The declaration and `routes` are two artifacts, and only the declaration is regenerated by
      // `generate:dts`. A stale declaration makes the assertions above check routes the app no longer has.
      // `router.getRoutes()` is used instead of `routes` because nested pages are
      // children: the raw array has `/blogs/[id]` but not `/blogs/[id]/edit`.
      // When this fails locally but not in CI: a running dev server watches `src/pages` and rewrites the declaration on
      // every page change, which hides the mismatch. In CI nothing watches, and `generate:dts` runs before the tests.
      const runtime = new Set(
        router
          .getRoutes()
          .map((route) => route.name)
          .filter((name): name is string => typeof name === 'string')
      )
      const declared = new Set(declaredPaths.map(({ name }) => name))

      expect([...declared].filter((name) => !runtime.has(name))).toEqual([])
      expect([...runtime].filter((name) => !declared.has(name) && !name.includes(catchAll))).toEqual([])
    })

    it('gives every route a component to render', () => {
      const withoutComponent = router
        .getRoutes()
        .filter((route) => !route.components || Object.keys(route.components).length === 0)

      expect(withoutComponent.map((route) => route.path)).toEqual([])
    })
  })
}
